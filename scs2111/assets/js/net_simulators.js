/* 1. OSI & TCP/IP ENCAPSULATION SIMULATOR */
function initOSIEpsulationSim() {
  const container = document.getElementById('osi-sim-container');
  if (!container) return;

  const steps = [
    { layer: '7. Application', pdu: 'Data', header: 'HTTP / SMTP Data payload', desc: 'Raw application payload generated by client user.' },
    { layer: '4. Transport', pdu: 'Segment', header: 'TCP Header (Src Port: 443, Dst Port: 52144, Seq#)', desc: 'Adds TCP/UDP port numbers, sequence numbers, and segment control flags.' },
    { layer: '3. Network', pdu: 'Packet', header: 'IP Header (Src IP: 192.168.1.15, Dst IP: 10.1.1.2, TTL)', desc: 'Adds logical source & destination IP addresses for inter-network routing.' },
    { layer: '2. Data Link', pdu: 'Frame', header: 'Ethernet Header (Src MAC: AA:BB, Dst MAC: CC:DD, FCS)', desc: 'Adds physical MAC addressing and Frame Check Sequence for local hop delivery.' },
    { layer: '1. Physical', pdu: 'Bits', header: '01101001 01110011 01101111...', desc: 'Encodes frames into electrical voltages, optical pulses, or RF radio waves.' }
  ];

  let currentStep = 0;

  function renderStep() {
    const item = steps[currentStep];
    container.innerHTML = `
      <div class="simulator-box">
        <div style="display:flex; justify-content:space-between; align-items:center; margin-bottom:1rem;">
          <h4 style="color:var(--primary-cyan); margin:0;">Encapsulation Process Step ${currentStep + 1} of ${steps.length}</h4>
          <span class="pdu-badge">Current PDU: ${item.pdu}</span>
        </div>

        <div style="background:rgba(16,23,42,0.9); padding:1rem; border-radius:var(--radius-sm); border:1px solid var(--border-color); margin-bottom:1rem;">
          <div style="font-weight:700; color:var(--text-main); font-size:1.1rem; margin-bottom:0.4rem;">${item.layer} Layer</div>
          <div style="color:var(--text-muted); font-size:0.9rem;">${item.desc}</div>
        </div>

        <div class="code-block" style="margin:1rem 0; border-color:var(--border-glow);">
          <div class="code-header"><span>Encapsulated Protocol Data Unit Header</span></div>
          <code style="color:var(--accent-amber); font-weight:600;">[ ${item.header} ] + [ Payload ]</code>
        </div>

        <div style="display:flex; gap:10px; margin-top:1rem;">
          <button class="btn btn-outline" id="enc-prev" ${currentStep === 0 ? 'disabled' : ''}>← Previous Layer</button>
          <button class="btn btn-primary" id="enc-next" ${currentStep === steps.length - 1 ? 'disabled' : ''}>Next Layer (Down Stack) →</button>
          <button class="btn btn-outline" id="enc-reset">Reset Flow</button>
        </div>
      </div>
    `;

    document.getElementById('enc-prev')?.addEventListener('click', () => { if (currentStep > 0) { currentStep--; renderStep(); } });
    document.getElementById('enc-next')?.addEventListener('click', () => { if (currentStep < steps.length - 1) { currentStep++; renderStep(); } });
    document.getElementById('enc-reset')?.addEventListener('click', () => { currentStep = 0; renderStep(); });
  }

  renderStep();
}

/* 2. BINARY SUBNETTING & VLSM CALCULATOR */
function initSubnetCalculatorSim() {
  const container = document.getElementById('subnet-sim-container');
  if (!container) return;

  function calculateSubnet(cidr) {
    const netBits = parseInt(cidr, 10);
    const hostBits = 32 - netBits;
    const totalHosts = Math.pow(2, hostBits);
    const usableHosts = hostBits <= 1 ? (hostBits === 1 ? 2 : 1) : totalHosts - 2;

    // Build binary mask representation
    let binaryMask = '';
    for (let i = 1; i <= 32; i++) {
      binaryMask += (i <= netBits) ? '1' : '0';
      if (i % 8 === 0 && i < 32) binaryMask += '.';
    }

    // Decimal mask calculation
    const octets = binaryMask.split('.').map(b => parseInt(b, 2));
    const decimalMask = octets.join('.');

    return { netBits, hostBits, totalHosts, usableHosts, binaryMask, decimalMask };
  }

  function update() {
    const cidrVal = document.getElementById('cidr-slider')?.value || 24;
    const data = calculateSubnet(cidrVal);

    const bitsContainer = document.getElementById('binary-bits-display');
    if (bitsContainer) {
      let bitsHtml = '';
      const rawBits = data.binaryMask.replace(/\./g, '');
      for (let i = 0; i < 32; i++) {
        const isNet = i < data.netBits;
        bitsHtml += `<div class="bit-box ${isNet ? 'net-bit' : 'host-bit'}">${rawBits[i]}</div>`;
        if ((i + 1) % 8 === 0 && i < 31) {
          bitsHtml += `<span class="octet-separator">.</span>`;
        }
      }
      bitsContainer.innerHTML = bitsHtml;
    }

    document.getElementById('res-cidr').textContent = `/${data.netBits}`;
    document.getElementById('res-mask').textContent = data.decimalMask;
    document.getElementById('res-netbits').textContent = data.netBits;
    document.getElementById('res-hostbits').textContent = data.hostBits;
    document.getElementById('res-totalhosts').textContent = data.totalHosts.toLocaleString();
    document.getElementById('res-usablehosts').textContent = data.usableHosts.toLocaleString();
  }

  container.innerHTML = `
    <div class="simulator-box">
      <h4 style="color:var(--primary-cyan); margin-bottom:1rem;">Interactive CIDR & Subnet Mask Bit Visualizer</h4>
      
      <div style="margin-bottom:1.5rem;">
        <label style="display:flex; justify-content:space-between; color:var(--text-main); font-weight:600; margin-bottom:0.5rem;">
          <span>Subnet Prefix Length (CIDR Prefix):</span>
          <span id="res-cidr" style="color:var(--primary-cyan); font-family:var(--font-code); font-size:1.1rem;">/24</span>
        </label>
        <input type="range" id="cidr-slider" min="8" max="30" value="24" style="width:100%; cursor:pointer; accent-color:var(--primary-cyan);">
      </div>

      <div style="margin-bottom:1rem;">
        <div style="font-size:0.85rem; color:var(--text-muted); margin-bottom:0.4rem;">32-Bit Subnet Mask Binary Representation:</div>
        <div id="binary-bits-display" class="binary-grid"></div>
        <div style="display:flex; gap:20px; font-size:0.8rem; margin-top:0.5rem;">
          <span style="color:var(--primary-cyan);">■ Network Bits</span>
          <span style="color:var(--accent-green);">■ Host Bits</span>
        </div>
      </div>

      <div class="grid-3" style="margin-top:1.5rem;">
        <div style="background:rgba(16,23,42,0.8); padding:1rem; border-radius:var(--radius-sm); border:1px solid var(--border-color);">
          <div style="font-size:0.8rem; color:var(--text-muted);">Decimal Subnet Mask</div>
          <div id="res-mask" style="font-family:var(--font-code); font-weight:700; color:var(--accent-amber); font-size:1.1rem; margin-top:4px;">255.255.255.0</div>
        </div>
        <div style="background:rgba(16,23,42,0.8); padding:1rem; border-radius:var(--radius-sm); border:1px solid var(--border-color);">
          <div style="font-size:0.8rem; color:var(--text-muted);">Network vs Host Split</div>
          <div style="font-family:var(--font-code); font-weight:700; color:var(--text-main); font-size:1rem; margin-top:4px;">
            <span id="res-netbits" style="color:var(--primary-cyan);">24</span> Net / <span id="res-hostbits" style="color:var(--accent-green);">8</span> Host
          </div>
        </div>
        <div style="background:rgba(16,23,42,0.8); padding:1rem; border-radius:var(--radius-sm); border:1px solid var(--border-color);">
          <div style="font-size:0.8rem; color:var(--text-muted);">Usable Hosts ($2^h - 2$)</div>
          <div id="res-usablehosts" style="font-family:var(--font-code); font-weight:700; color:var(--accent-green); font-size:1.1rem; margin-top:4px;">254</div>
        </div>
      </div>
    </div>
  `;

  document.getElementById('cidr-slider')?.addEventListener('input', update);
  update();
}

/* 3. TCP 3-WAY HANDSHAKE ANIMATOR */
function initTCPHandshakeSim() {
  const container = document.getElementById('tcp-sim-container');
  if (!container) return;

  let state = 0; // 0: initial, 1: SYN sent, 2: SYN-ACK received, 3: ACK sent (Established)

  const stepsData = [
    { title: 'Disconnected / Closed State', clientState: 'CLOSED', serverState: 'LISTEN', packet: null, desc: 'Client and Server waiting to initiate TCP stream.' },
    { title: 'Step 1: SYN (Synchronize)', clientState: 'SYN-SENT', serverState: 'LISTEN', packet: 'Client → Server: [SYN, Seq=100]', desc: 'Client sends SYN packet with an Initial Sequence Number (ISN).' },
    { title: 'Step 2: SYN-ACK (Synchronize-Acknowledge)', clientState: 'SYN-SENT', serverState: 'SYN-RECEIVED', packet: 'Server → Client: [SYN-ACK, Seq=300, Ack=101]', desc: 'Server acknowledges client SYN (Ack=101) and sends its own SYN (Seq=300).' },
    { title: 'Step 3: ACK (Acknowledge)', clientState: 'ESTABLISHED', serverState: 'ESTABLISHED', packet: 'Client → Server: [ACK, Seq=101, Ack=301]', desc: 'Client acknowledges server SYN (Ack=301). Connection is now ESTABLISHED for full-duplex data transfer!' }
  ];

  function render() {
    const cur = stepsData[state];
    container.innerHTML = `
      <div class="simulator-box">
        <h4 style="color:var(--primary-cyan); margin-bottom:1rem;">TCP 3-Way Handshake Connection State Animator</h4>

        <div style="display:flex; justify-content:space-between; align-items:center; position:relative; padding:2rem 1rem; background:rgba(16,23,42,0.6); border-radius:var(--radius-md); border:1px solid var(--border-color);">
          <div class="node-host ${state >= 1 ? 'active' : ''}">
            <div>CLIENT</div>
            <div style="color:var(--primary-cyan); font-size:0.7rem; margin-top:4px;">${cur.clientState}</div>
          </div>

          <div style="flex:1; margin:0 2rem; text-align:center; position:relative;">
            <div style="height:4px; background:rgba(56,189,248,0.2); border-radius:2px;"></div>
            ${cur.packet ? `
              <div style="position:absolute; top:-25px; left:50%; transform:translateX(-50%); background:var(--bg-dark); border:1px solid var(--primary-cyan); padding:4px 12px; border-radius:12px; color:var(--accent-amber); font-family:var(--font-code); font-size:0.8rem; box-shadow:0 0 10px rgba(56,189,248,0.3);">
                ${cur.packet}
              </div>
            ` : ''}
          </div>

          <div class="node-host ${state >= 2 ? 'active' : ''}">
            <div>SERVER</div>
            <div style="color:var(--accent-green); font-size:0.7rem; margin-top:4px;">${cur.serverState}</div>
          </div>
        </div>

        <div style="margin-top:1.5rem; background:rgba(16,23,42,0.8); padding:1rem; border-radius:var(--radius-sm); border:1px solid var(--border-color);">
          <div style="font-weight:700; color:var(--primary-cyan);">${cur.title}</div>
          <div style="color:var(--text-muted); font-size:0.9rem; margin-top:4px;">${cur.desc}</div>
        </div>

        <div style="display:flex; gap:10px; margin-top:1rem;">
          <button class="btn btn-primary" id="tcp-step-btn" ${state === 3 ? 'disabled' : ''}>Advance Handshake Step →</button>
          <button class="btn btn-outline" id="tcp-reset-btn">Reset Connection</button>
        </div>
      </div>
    `;

    document.getElementById('tcp-step-btn')?.addEventListener('click', () => { if (state < 3) { state++; render(); } });
    document.getElementById('tcp-reset-btn')?.addEventListener('click', () => { state = 0; render(); });
  }

  render();
}

