/* 6. NETWORK CABINET & INDUSTRIAL TROUBLESHOOTING SANDBOX */
function initTroubleshootingSandbox() {
  const container = document.getElementById('troubleshoot-sim-container');
  if (!container) return;

  const tickets = [
    {
      id: 'TCK-101',
      title: 'Whole Office Network Down (Fiber Link Indicator OFF)',
      scenario: 'The core fiber converter RX light is extinguished. Users report total internet outage.',
      cause: 'Primary ISP fiber cut or dirty fiber connector transceiver link.',
      solution: 'Check physical fiber cable bend radius, inspect TX/RX fiber lights on converter box, and initiate immediate failover to secondary TelOne ISP WAN port link on firewall while opening high-priority ticket with primary ISP.'
    },
    {
      id: 'TCK-102',
      title: 'CCTV PoE Cameras Disconnected After Cable Move',
      scenario: '3 IP Cameras went offline right after an intern rearranged cables in the network rack cabinet.',
      cause: 'Cables were plugged into non-PoE access switch ports or assigned to incorrect VLAN IDs.',
      solution: 'Verify cables are connected specifically to 802.3af/at PoE-enabled switch ports (Ports 1-12) and confirm port VLAN membership matches the dedicated Surveillance VLAN.'
    }
  ];

  let selectedIdx = 0;

  function render() {
    const t = tickets[selectedIdx];
    container.innerHTML = `
      <div class="simulator-box">
        <h4 style="color:var(--accent-green); margin-bottom:1rem;">Industrial Attachment Field Diagnostic Ticket</h4>

        <div style="display:flex; gap:10px; margin-bottom:1rem;">
          ${tickets.map((tk, idx) => `
            <button class="btn ${idx === selectedIdx ? 'btn-primary' : 'btn-outline'}" onclick="window.setTroubleshootTicket(${idx})">
              ${tk.id}
            </button>
          `).join('')}
        </div>

        <div class="callout callout-warning">
          <div class="callout-title">⚠️ Scenario Description: ${t.title}</div>
          <p style="margin:0;">${t.scenario}</p>
        </div>

        <div class="card" style="margin:1rem 0;">
          <h5 style="color:var(--accent-amber); margin-bottom:0.4rem;">Root Cause Analysis:</h5>
          <p>${t.cause}</p>

          <h5 style="color:var(--accent-green); margin-bottom:0.4rem; margin-top:1rem;">Standard Operating Procedure (SOP) Solution:</h5>
          <p>${t.solution}</p>
        </div>
      </div>
    `;
  }

  window.setTroubleshootTicket = function(idx) {
    selectedIdx = idx;
    render();
  };

  render();
}
